"""Small helpers shared by the Hot Seat (How Well Do You Know) service modules."""

from __future__ import annotations

import uuid

from fastapi import HTTPException, status
from sqlalchemy.orm import Session

from app.db.models.experience import ExperienceInstance

DEFAULT_GAME_CONFIG = {
    "mode": "default",
    "num_questions": 5,
    "intimacy_level": "personal",
    "min_answer_length": 3,
}

# How long guessers get on each live question.
GUESS_SECONDS = 30
# A guess that reaches the server this long after the deadline still counts
# (clock/latency slack); anything later is rejected.
GUESS_GRACE_SECONDS = 1.0
# Points for fooling another player with your fake answer (party mode).
FOOL_POINTS = 50
CORRECT_POINTS = 100

# Longest wrong answer the main person (or AI) may put on a card.
MAX_CHOICE_LEN = 120
# How many times a single wrong answer may be regenerated by AI.
MAX_REGENERATIONS = 3
# Used only when the AI call fails; the main person can edit these on review.
FALLBACK_DISTRACTORS = ["Option A", "Option B", "Option C", "Option D", "Option E"]


def clean_text(text: object) -> str:
    """Trim and collapse internal whitespace so 'Pizza ' and 'pizza' compare equal."""
    return " ".join(str(text or "").split())


def norm(text: object) -> str:
    return clean_text(text).casefold()


def unique_wrong_answers(
    candidates: list, taken: list[str], limit: int | None = None
) -> list[str]:
    """Clean candidates, dropping blanks and anything equal to ``taken`` or an
    earlier candidate (case-insensitive). The database has a unique constraint on
    (round, choice_text); inserting a duplicate would otherwise fail the request."""
    seen = {norm(t) for t in taken}
    out: list[str] = []
    for cand in candidates:
        text = clean_text(cand)[:MAX_CHOICE_LEN].strip()
        if not text or norm(text) in seen:
            continue
        seen.add(norm(text))
        out.append(text)
        if limit is not None and len(out) >= limit:
            break
    return out


def lock_experience(
    db: Session, experience_id: uuid.UUID, skip_locked: bool = False
) -> ExperienceInstance | None:
    """Re-read the experience row with a row lock so concurrent edits, confirms
    and state changes are applied one at a time, each seeing the others' result.

    With ``skip_locked`` the call returns None instead of waiting when another
    request already holds the row (used by background "is this phase over?"
    checks, which must never queue up behind a slow request)."""
    exp = (
        db.query(ExperienceInstance)
        .filter(ExperienceInstance.id == experience_id)
        .with_for_update(skip_locked=skip_locked)
        .populate_existing()
        .first()
    )
    if not exp and not skip_locked:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="Experience not found"
        )
    return exp


def conflict(code: str, message: str) -> HTTPException:
    return HTTPException(
        status_code=status.HTTP_409_CONFLICT,
        detail={"code": code, "message": message},
    )
